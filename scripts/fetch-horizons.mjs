/**
 * fetch-horizons.mjs — regenerate the reference data used by the tracker.
 *
 * Queries the NASA/JPL Horizons API (https://ssd.jpl.nasa.gov/horizons/) for
 * Voyager 1 (-31) and Voyager 2 (-32) and writes:
 *
 *   src/data/horizons.generated.ts   — epoch state vectors + monthly history
 *   scripts/validation.generated.json — geocentric ranges used by
 *                                       validate-model.ts (not shipped)
 *
 * Usage:  node scripts/fetch-horizons.mjs
 *
 * Nothing in the browser calls Horizons; the site only ships the numbers
 * this script writes, so every figure can be traced to a reproducible query.
 */

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const API = 'https://ssd.jpl.nasa.gov/api/horizons.api';
const AU_KM = 149_597_870.7;

/** Epoch for the tracker state vectors (TDB; ~69 s ahead of UTC — negligible here). */
const EPOCH = '2026-09-01';

const CRAFT = {
  voyager1: { id: '-31', start: '1977-09-06' },
  voyager2: { id: '-32', start: '1977-08-21' },
};

async function horizons(params) {
  const q = new URLSearchParams({
    format: 'text',
    OBJ_DATA: "'NO'",
    MAKE_EPHEM: "'YES'",
    EPHEM_TYPE: "'VECTORS'",
    REF_PLANE: "'ECLIPTIC'",
    OUT_UNITS: "'KM-S'",
    CSV_FORMAT: "'YES'",
    ...Object.fromEntries(Object.entries(params).map(([k, v]) => [k, `'${v}'`])),
  });
  const res = await fetch(`${API}?${q}`);
  if (!res.ok) throw new Error(`Horizons HTTP ${res.status}`);
  const text = await res.text();
  const block = text.split('$$SOE')[1]?.split('$$EOE')[0];
  if (!block) throw new Error(`No ephemeris block returned:\n${text.slice(0, 800)}`);
  return block
    .trim()
    .split('\n')
    .map((line) => line.split(',').map((s) => s.trim()))
    .map((cols) => ({
      jd: Number(cols[0]),
      date: cols[1].replace('A.D. ', '').slice(0, 11),
      v: cols.slice(2).filter(Boolean).map(Number),
    }));
}

/** Convert "2026-Sep-01" to "2026-09-01". */
const MONTHS = { Jan: '01', Feb: '02', Mar: '03', Apr: '04', May: '05', Jun: '06', Jul: '07', Aug: '08', Sep: '09', Oct: '10', Nov: '11', Dec: '12' };
const isoDate = (d) => `${d.slice(0, 4)}-${MONTHS[d.slice(5, 8)]}-${d.slice(9, 11)}`;

const out = { epoch: {}, history: {} };
const validation = {};

for (const [key, { id, start }] of Object.entries(CRAFT)) {
  // 1. State vector at the tracker epoch (solar-system barycentric, ecliptic J2000).
  const [state] = await horizons({
    COMMAND: id,
    CENTER: '500@0',
    START_TIME: EPOCH,
    STOP_TIME: '2026-09-02',
    STEP_SIZE: '1d',
    VEC_TABLE: '2',
  });
  out.epoch[key] = { r: state.v.slice(0, 3), v: state.v.slice(3, 6) };

  // 2. Monthly heliocentric distance and speed, launch → 2035.
  const rows = await horizons({
    COMMAND: id,
    CENTER: '500@10',
    START_TIME: start,
    STOP_TIME: '2035-01-01',
    STEP_SIZE: '1 mo',
    VEC_TABLE: '2',
  });
  out.history[key] = rows.map((row) => {
    const [x, y, z, vx, vy, vz] = row.v;
    return [
      isoDate(row.date),
      Number((Math.hypot(x, y, z) / AU_KM).toFixed(3)),
      Number(Math.hypot(vx, vy, vz).toFixed(2)),
    ];
  });

  // 3. Geocentric range every 5 days, 2024 → 2032, for model validation only.
  const geo = await horizons({
    COMMAND: id,
    CENTER: '500@399',
    START_TIME: '2024-01-01',
    STOP_TIME: '2032-01-01',
    STEP_SIZE: '5d',
    VEC_TABLE: '3',
  });
  validation[key] = geo.map((row) => ({ jd: row.jd, rangeKm: row.v[7], rangeRateKmS: row.v[8] }));
}

// 4. The Sun's offset from the solar-system barycentre, monthly 2020–2040.
//    Far-away spacecraft effectively orbit the barycentre, while the Sun
//    wobbles around it by up to ~1.4 million km (mostly Jupiter's pull).
const sunRows = await horizons({
  COMMAND: '10',
  CENTER: '500@0',
  START_TIME: '2020-01-01',
  STOP_TIME: '2040-01-01',
  STEP_SIZE: '1 mo',
  VEC_TABLE: '2',
});
const sunStart = isoDate(sunRows[0].date);
const sun = sunRows.map((row) => row.v.slice(0, 3).map((n) => Math.round(n)));

const header = `/**
 * AUTO-GENERATED by scripts/fetch-horizons.mjs — do not edit by hand.
 *
 * Source: NASA/JPL Horizons System (https://ssd.jpl.nasa.gov/horizons/),
 * targets -31 (Voyager 1), -32 (Voyager 2) and 10 (Sun), ecliptic J2000.
 * EPOCH_STATE and SUN_BARY are barycentric; HISTORY is heliocentric.
 * Generated: ${new Date().toISOString().slice(0, 10)}
 */
`;

const ts = `${header}
/** Epoch of the state vectors below (TDB). */
export const EPOCH_ISO = '${EPOCH}T00:00:00Z';

/** Barycentric position (km) and velocity (km/s) at EPOCH_ISO. */
export const EPOCH_STATE = ${JSON.stringify(out.epoch, null, 2)} as const;

/** Sun position relative to the solar-system barycentre (km), one row per month from SUN_TABLE_START. */
export const SUN_TABLE_START = '${sunStart}';
export const SUN_BARY: [number, number, number][] = ${JSON.stringify(sun)};

/**
 * Monthly samples: [date, heliocentric distance in AU, heliocentric speed in km/s].
 * Dates after the generation date are JPL's predicted trajectory.
 */
export const HISTORY: Record<'voyager1' | 'voyager2', [string, number, number][]> = ${JSON.stringify(out.history)};
`;

writeFileSync(resolve(ROOT, 'src/data/horizons.generated.ts'), ts);
writeFileSync(resolve(ROOT, 'scripts/validation.generated.json'), JSON.stringify(validation));
console.log(
  `Wrote horizons.generated.ts (${out.history.voyager1.length} + ${out.history.voyager2.length} samples) and validation data.`,
);
